package com.practiceproject.ticket;

import com.google.zxing.BarcodeFormat;
import com.google.zxing.EncodeHintType;
import com.google.zxing.client.j2se.MatrixToImageWriter;
import com.google.zxing.qrcode.QRCodeWriter;
import com.google.zxing.qrcode.decoder.ErrorCorrectionLevel;
import com.practiceproject.common.Tokens;
import java.io.ByteArrayOutputStream;
import java.util.Map;
import java.util.Optional;
import org.springframework.stereotype.Service;

/**
 * Ticket codes and QR images.
 *
 * The QR payload is {@code PP1:<reference>:<ticketCode>}. The ticket code is 12 random
 * characters (about 59 bits) generated by SecureRandom and stored on the booking, so it
 * cannot be guessed. The door scanner sends the payload to /api/admin/checkin.
 */
@Service
public class TicketService {

    public record ParsedCode(String reference, String ticketCode) {}

    public String newTicketCode() {
        return Tokens.readableCode(12);
    }

    public String payload(String reference, String ticketCode) {
        return "PP1:" + reference + ":" + ticketCode;
    }

    /** Accepts the full QR payload, or "REFERENCE TICKETCODE" typed by staff. */
    public Optional<ParsedCode> parse(String raw) {
        if (raw == null) {
            return Optional.empty();
        }
        String value = raw.trim().toUpperCase();
        String[] parts = value.startsWith("PP1:") ? value.substring(4).split(":") : value.split("[\\s:]+");
        if (parts.length != 2 || !parts[0].matches("[A-Z0-9]{6,20}") || !parts[1].matches("[A-Z0-9]{8,20}")) {
            return Optional.empty();
        }
        return Optional.of(new ParsedCode(parts[0], parts[1]));
    }

    public byte[] qrPng(String payload) {
        try {
            var matrix = new QRCodeWriter().encode(payload, BarcodeFormat.QR_CODE, 360, 360,
                    Map.of(EncodeHintType.ERROR_CORRECTION, ErrorCorrectionLevel.M, EncodeHintType.MARGIN, 1));
            var out = new ByteArrayOutputStream();
            MatrixToImageWriter.writeToStream(matrix, "PNG", out);
            return out.toByteArray();
        } catch (Exception e) {
            throw new IllegalStateException("Could not render QR code", e);
        }
    }
}
